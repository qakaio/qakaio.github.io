function getStoredLang() {
  return localStorage.getItem('lang') || 'pt';
}

let cachedI18nElements = null;
let cachedLangOptions = null;

function setLang(lang) {
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

  if (!cachedI18nElements) cachedI18nElements = document.querySelectorAll('[data-i18n]');
  if (!cachedLangOptions) cachedLangOptions = document.querySelectorAll('.lang-option');

  cachedI18nElements.forEach((el) => el.classList.add('lang-switching'));

  setTimeout(() => {
    cachedI18nElements.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const val = translations[lang][key];
      if (val) el.textContent = val;
      el.classList.remove('lang-switching');
    });

    cachedLangOptions.forEach((opt) => {
      opt.classList.toggle('active', opt.dataset.lang === lang);
    });

    document.title = lang === 'pt'
      ? 'Kaio Garcia | Neurociência & Comportamento'
      : 'Kaio Garcia | Neuroscience & Behavior';
  }, 200);
}

function initI18n() {
  const lang = getStoredLang();
  setLang(lang);

  document.getElementById('langToggle').addEventListener('click', (e) => {
    const option = e.target.closest('.lang-option');
    const currentLang = getStoredLang();
    const newLang = option ? option.dataset.lang : (currentLang === 'pt' ? 'en' : 'pt');
    if (newLang && newLang !== currentLang) {
      setLang(newLang);
    }
  });
}

document.addEventListener('DOMContentLoaded', initI18n);
